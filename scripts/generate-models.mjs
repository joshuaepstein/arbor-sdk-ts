#!/usr/bin/env node
/**
 * Generates TypeScript models and resource-type constants from a checkout of
 * the PHP SDK (https://github.com/arbor-education/sis-sdk-php).
 *
 *   node scripts/generate-models.mjs /path/to/sis-sdk-php
 *
 * Writes src/models/** and src/resource/resource-type.ts. Re-run it after
 * pulling upstream to pick up new or changed models.
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const phpRoot = process.argv[2];
if (!phpRoot) {
  console.error('Usage: node scripts/generate-models.mjs /path/to/sis-sdk-php');
  process.exit(1);
}
const PHP_SRC = resolve(phpRoot, 'src/Arbor');
if (!existsSync(join(PHP_SRC, 'Model'))) {
  console.error(`No src/Arbor/Model directory under ${phpRoot}`);
  process.exit(1);
}

const MODEL_DIR = join(PHP_SRC, 'Model');
const RESOURCE_DIR = join(PHP_SRC, 'Resource');
const OUT_MODELS = join(ROOT, 'src/models');
const OUT_RESOURCE = join(ROOT, 'src/resource/resource-type.ts');

// Files in Model/ that are SDK infrastructure, not resources.
const NON_MODELS = new Set(['ModelBase', 'Collection', 'Hydrator', 'Exception']);
// Names the package index already exports; a model with one of these names would clash.
const RESERVED = new Set([
  'ModelBase', 'Collection', 'Hydrator', 'Query', 'Operator', 'Change', 'RestGateway', 'HttpClient',
  'HttpMethod', 'UploadFile', 'ResourceType', 'ArborError', 'ModelError', 'QueryError', 'GatewayError',
  'ServerError', 'ResourceNotFoundError', 'ServerValidationError', 'createClient',
]);
const BASE_METHODS = new Set([
  'getResourceUrl', 'setResourceUrl', 'getResourceId', 'getApiGateway', 'getProperties', 'setProperties',
  'getProperty', 'setProperty', 'getCollectionProperty', 'getResourceType', 'setResourceType',
  'getDisplayName', 'setDisplayName', 'getUserTags', 'setUserTags', 'getId', 'getUniqueObjectId',
]);

const GENERATED_HEADER =
  '// Generated by scripts/generate-models.mjs from arbor-education/sis-sdk-php. Do not edit by hand.\n';

// ---------------------------------------------------------------- resource types

function parseConstFile(file) {
  const out = [];
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(/const\s+([A-Z0-9_]+)\s*=\s*'([^']*)'\s*;/g)) out.push([m[1], m[2]]);
  return out;
}

/** module ('' for core) → [[CONST, value]] */
const resourceTypes = new Map();
resourceTypes.set('', parseConstFile(join(RESOURCE_DIR, 'ResourceType.php')));
for (const entry of readdirSync(RESOURCE_DIR)) {
  const file = join(RESOURCE_DIR, entry, 'ResourceType.php');
  if (statSync(join(RESOURCE_DIR, entry)).isDirectory() && existsSync(file)) {
    resourceTypes.set(entry, parseConstFile(file));
  }
}
const resourceLookup = new Map(); // `${module}::${CONST}` → value
for (const [mod, list] of resourceTypes) for (const [k, v] of list) resourceLookup.set(`${mod}::${k}`, v);

// ---------------------------------------------------------------- models

/** Collect model files: [{ module, name, file }] */
const modelFiles = [];
for (const entry of readdirSync(MODEL_DIR)) {
  const full = join(MODEL_DIR, entry);
  if (statSync(full).isDirectory()) {
    if (entry === 'Hydrator') continue;
    for (const f of readdirSync(full)) {
      if (f.endsWith('.php')) modelFiles.push({ module: entry, name: f.slice(0, -4), file: join(full, f) });
    }
  } else if (entry.endsWith('.php') && !NON_MODELS.has(entry.slice(0, -4))) {
    modelFiles.push({ module: '', name: entry.slice(0, -4), file: full });
  }
}
modelFiles.sort((a, b) => (a.module + '/' + a.name).localeCompare(b.module + '/' + b.name));
const known = new Set(modelFiles.map((m) => `${m.module}/${m.name}`));

const warnings = [];

/** Resolve a PHP type to { kind: 'scalar', ts } or { kind: 'model', module, name } */
function resolvePhpType(raw, currentModule) {
  let t = (raw ?? '').trim().replace(/^\?/, '');
  if (!t) return { kind: 'scalar', ts: 'unknown' };
  switch (t.replace(/^\\/, '')) {
    case 'string': return { kind: 'scalar', ts: 'string' };
    case 'int': case 'float': case 'double': return { kind: 'scalar', ts: 'number' };
    case 'bool': case 'boolean': return { kind: 'scalar', ts: 'boolean' };
    case 'DateTime': case 'DateTimeInterface': return { kind: 'scalar', ts: 'Date' };
    case 'array': return { kind: 'scalar', ts: 'unknown[]' };
    case 'mixed': return { kind: 'scalar', ts: 'unknown' };
    case 'ModelBase': case 'Arbor\\Model\\ModelBase': return { kind: 'base' };
  }
  const parts = t.replace(/^\\/, '').split('\\');
  let module, name;
  if (parts[0] === 'Arbor' && parts[1] === 'Model') {
    if (parts.length === 3) [module, name] = ['', parts[2]];
    else if (parts.length === 4) [module, name] = [parts[2], parts[3]];
  } else if (parts.length === 1) {
    [module, name] = [currentModule, parts[0]];
    if (!known.has(`${module}/${name}`) && known.has(`/${name}`)) module = '';
  }
  if (name !== undefined && known.has(`${module}/${name}`)) return { kind: 'model', module, name };
  return { kind: 'base' };
}

function parseModel({ module, name, file }) {
  const src = readFileSync(file, 'utf8');
  const constants = [...src.matchAll(/public\s+const\s+([A-Z0-9_]+)\s*=\s*'([^']*)'\s*;/g)].map((m) => [m[1], m[2]]);

  const rt = /protected\s+\$_resourceType\s*=\s*ResourceType::([A-Z0-9_]+)\s*;/.exec(src);
  const useRes = /use\s+Arbor\\Resource\\(?:(\w+)\\)?ResourceType\s*;/.exec(src);
  const resModule = useRes?.[1] ?? '';
  let resourceType = rt ? resourceLookup.get(`${resModule}::${rt[1]}`) : undefined;
  if (!resourceType) {
    resourceType = module ? `${module}_${name}` : name;
    warnings.push(`${module}/${name}: could not resolve resource type, using '${resourceType}'`);
  }

  const methods = [];
  const re = /\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*public\s+function\s+(get|set)(\w+)\s*\(([^)]*)\)\s*\{([^}]*)\}/g;
  for (const m of src.matchAll(re)) {
    const [, doc, kind, suffix, params, body] = m;
    const method = kind + suffix;
    if (BASE_METHODS.has(method)) continue;
    if (kind === 'get') {
      const prop = /\$this->(getProperty|getCollectionProperty)\('([^']+)'\)/.exec(body);
      if (!prop) continue;
      const ret = /@return\s+(\S+)/.exec(doc)?.[1] ?? '';
      const isCollection = prop[1] === 'getCollectionProperty';
      let type;
      if (isCollection) {
        const item = ret.split('|').find((p) => p.endsWith('[]'))?.slice(0, -2);
        type = { kind: 'collection', item: item ? resolvePhpType(item, module) : { kind: 'base' } };
      } else {
        type = resolvePhpType(ret.split('|').find((p) => p !== 'null'), module);
      }
      methods.push({ kind, method, property: prop[2], type });
    } else {
      const prop = /\$this->setProperty\('([^']+)'\s*,\s*\$(\w+)\)/.exec(body);
      if (!prop) continue;
      const pm = /^\s*(?:(\??[\\\w]+)\s+)?\$(\w+)/.exec(params);
      const docParam = /@param\s+(\S+)\s+\$/.exec(doc)?.[1];
      const type = resolvePhpType(pm?.[1] ?? docParam, module);
      methods.push({ kind, method, property: prop[1], param: pm?.[2] ?? prop[2], type });
    }
  }
  return { module, name, resourceType, constants, methods };
}

const models = modelFiles.map(parseModel);

// ---------------------------------------------------------------- emit

const RESERVED_WORDS = new Set([
  'break', 'case', 'catch', 'class', 'const', 'continue', 'debugger', 'default', 'delete', 'do', 'else', 'enum',
  'export', 'extends', 'false', 'finally', 'for', 'function', 'if', 'import', 'in', 'instanceof', 'new', 'null',
  'return', 'super', 'switch', 'this', 'throw', 'true', 'try', 'typeof', 'var', 'void', 'while', 'with', 'yield',
  'let', 'static', 'implements', 'interface', 'package', 'private', 'protected', 'public', 'await', 'arguments', 'eval',
]);
const safeParam = (p) => (RESERVED_WORDS.has(p) ? `${p}Value` : p);

function emitModel(model) {
  const { module, name } = model;
  const rel = module ? '../' : './'; // path from this file to src/models/
  const imports = new Map(); // localName → path
  const localName = (ref) => {
    if (ref.module === module && ref.name === name) return name;
    let local = ref.module ? `${ref.module}${ref.name}` : ref.name;
    if (local === name) local = `Arbor${ref.name}`;
    const path = ref.module
      ? (module === ref.module ? `./${ref.name}.js` : `${rel}${ref.module}/${ref.name}.js`)
      : `${rel}${ref.name}.js`;
    if (local === ref.name) imports.set(local, `import type { ${ref.name} } from '${path}';`);
    else imports.set(local, `import type { ${ref.name} as ${local} } from '${path}';`);
    return local;
  };
  const tsType = (t) => {
    if (t.kind === 'scalar') return t.ts;
    if (t.kind === 'base') return 'ModelBase';
    if (t.kind === 'model') return localName(t);
    if (t.kind === 'collection') return `Collection<${tsType(t.item)}>`;
    throw new Error(`Unknown type ${JSON.stringify(t)}`);
  };

  const lines = [];
  const seenConst = new Set(['RESOURCE_TYPE']);
  lines.push(`export class ${name} extends ModelBase {`);
  lines.push(`  static readonly RESOURCE_TYPE = '${model.resourceType}';`);
  for (const [k, v] of model.constants) {
    if (seenConst.has(k)) {
      warnings.push(`${module}/${name}: skipped duplicate constant ${k}`);
      continue;
    }
    seenConst.add(k);
    lines.push(`  static readonly ${k} = '${v}';`);
  }
  lines.push('');
  lines.push(`  constructor(properties: Record<string, unknown> = {}, gateway: Gateway | null = ModelBase.getDefaultGateway()) {`);
  lines.push(`    super(${name}.RESOURCE_TYPE, properties, gateway);`);
  lines.push('  }');
  lines.push('');
  lines.push(`  static query(query: Query = new Query()): Promise<Collection<${name}>> {`);
  lines.push(`    return ModelBase.requireDefaultGateway('${name}.query').query<${name}>(query.setResourceType(${name}.RESOURCE_TYPE));`);
  lines.push('  }');
  lines.push('');
  lines.push(`  static retrieve(id: string | number): Promise<${name}> {`);
  lines.push(`    return ModelBase.requireDefaultGateway('${name}.retrieve').retrieve<${name}>(${name}.RESOURCE_TYPE, id);`);
  lines.push('  }');

  const seenMethods = new Set();
  for (const m of model.methods) {
    if (seenMethods.has(m.method)) continue;
    seenMethods.add(m.method);
    lines.push('');
    if (m.kind === 'get') {
      if (m.type.kind === 'collection') {
        lines.push(`  ${m.method}(): ${tsType(m.type)} {`);
        lines.push(`    return this.getCollectionProperty<${tsType(m.type.item)}>('${m.property}');`);
      } else {
        const t = tsType(m.type);
        lines.push(`  ${m.method}(): ${t} | null {`);
        if (t === 'Date') lines.push(`    return this.getDateProperty('${m.property}');`);
        else lines.push(`    return this.getProperty<${t}>('${m.property}');`);
      }
    } else {
      const p = safeParam(m.param);
      lines.push(`  ${m.method}(${p}: ${tsType(m.type)} | null = null): void {`);
      lines.push(`    this.setProperty('${m.property}', ${p});`);
    }
    lines.push('  }');
  }
  lines.push('}');

  const core = module ? '../../' : '../';
  const usesCollection = true; // query() always returns a Collection
  const header = [
    GENERATED_HEADER,
    `import type { Gateway } from '${core}api/gateway.js';`,
    usesCollection ? `import type { Collection } from '${core}model/collection.js';` : null,
    `import { ModelBase } from '${core}model/model-base.js';`,
    `import { Query } from '${core}query/query.js';`,
    ...[...imports.keys()].sort().map((k) => imports.get(k)),
  ].filter(Boolean);
  return `${header.join('\n')}\n\n${lines.join('\n')}\n`;
}

rmSync(OUT_MODELS, { recursive: true, force: true });
mkdirSync(OUT_MODELS, { recursive: true });

const byModule = new Map();
for (const model of models) {
  if (!model.module && RESERVED.has(model.name)) warnings.push(`Model ${model.name} clashes with an SDK export`);
  const dir = model.module ? join(OUT_MODELS, model.module) : OUT_MODELS;
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, `${model.name}.ts`), emitModel(model));
  if (!byModule.has(model.module)) byModule.set(model.module, []);
  byModule.get(model.module).push(model);
}

// Barrels: src/models/index.ts (core) and src/models/<Module>/index.ts
for (const [mod, list] of byModule) {
  const dir = mod ? join(OUT_MODELS, mod) : OUT_MODELS;
  const body = list.map((m) => `export { ${m.name} } from './${m.name}.js';`).join('\n');
  const nested = mod
    ? ''
    : '\n' + [...byModule.keys()].filter(Boolean).sort().map((k) => `export * as ${k} from './${k}/index.js';`).join('\n');
  writeFileSync(join(dir, 'index.ts'), `${GENERATED_HEADER}\n${body}\n${nested}\n`);
}

// Registry: maps resource type strings to model classes for hydration.
{
  const lines = [GENERATED_HEADER, `import { registerModel } from '../model/registry.js';`];
  const entries = [];
  for (const m of models) {
    const local = m.module ? `${m.module}_${m.name}` : m.name;
    const path = m.module ? `./${m.module}/${m.name}.js` : `./${m.name}.js`;
    lines.push(local === m.name ? `import { ${m.name} } from '${path}';` : `import { ${m.name} as ${local} } from '${path}';`);
    entries.push(`  [${local}.RESOURCE_TYPE, (g) => new ${local}({}, g)],`);
  }
  lines.push('');
  lines.push(`let registered = false;`);
  lines.push('');
  lines.push(`/** Registers every generated model so API responses hydrate into typed classes. Safe to call repeatedly. */`);
  lines.push(`export function registerGeneratedModels(): void {`);
  lines.push(`  if (registered) return;`);
  lines.push(`  registered = true;`);
  lines.push(`  for (const [type, factory] of ENTRIES) registerModel(type, factory);`);
  lines.push(`}`);
  lines.push('');
  lines.push(`const ENTRIES: [string, Parameters<typeof registerModel>[1]][] = [`);
  lines.push(...entries);
  lines.push(`];`);
  writeFileSync(join(OUT_MODELS, 'registry.generated.ts'), lines.join('\n') + '\n');
}

// Resource types
{
  const out = [GENERATED_HEADER];
  for (const [mod, list] of [...resourceTypes].sort(([a], [b]) => a.localeCompare(b))) {
    const constName = mod ? `${mod}ResourceType` : 'ResourceType';
    out.push(`export const ${constName} = {`);
    for (const [k, v] of list) out.push(`  ${k}: '${v}',`);
    out.push(`} as const;`);
    out.push(`export type ${constName} = (typeof ${constName})[keyof typeof ${constName}];`);
    out.push('');
  }
  mkdirSync(dirname(OUT_RESOURCE), { recursive: true });
  writeFileSync(OUT_RESOURCE, out.join('\n'));
}

const methodCount = models.reduce((n, m) => n + m.methods.length, 0);
console.log(`Generated ${models.length} models (${methodCount} accessors) across ${byModule.size} modules.`);
console.log(`Resource types: ${[...resourceTypes].map(([m, l]) => `${m || 'core'}=${l.length}`).join(', ')}`);
if (warnings.length) {
  console.log(`\n${warnings.length} warning(s):`);
  for (const w of warnings) console.log(`  - ${w}`);
}
